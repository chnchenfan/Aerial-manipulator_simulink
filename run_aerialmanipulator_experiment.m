function result = run_aerialmanipulator_experiment(config)
%RUN_AERIALMANIPULATOR_EXPERIMENT Run one batch experiment and save metrics.

if nargin < 1
    config = struct();
end

config = with_default_config(config);
model_name = config.sim.model_name;

if ~exist(config.output.save_dir, 'dir')
    mkdir(config.output.save_dir);
end

sim_tuning_runtime('reset_all');
sim_tuning_runtime('set_config', config);

warning('off', 'all');
load_system([model_name '.slx']);
set_param(model_name, 'StopTime', num2str(config.sim.stop_time));

evalc(sprintf('sim(''%s'');', model_name));
signals = sim_tuning_runtime('get_log');
metrics = evaluate_aerialmanipulator_results(signals, config);

result = struct();
result.config = config;
result.signals = signals;
result.metrics = metrics;
result.created_at = datestr(now, 'yyyy-mm-dd HH:MM:SS');

if config.output.save_results
    filename = build_result_filename(config);
    save(filename, 'result');
    result.output_file = filename;
end

