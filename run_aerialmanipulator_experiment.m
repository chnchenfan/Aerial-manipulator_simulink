function filename = build_result_filename(config)
timestamp = datestr(now, 'yyyymmdd_HHMMSS');
filename = fullfile(config.output.save_dir, ...
    sprintf('%s_%s.mat', config.output.label, timestamp));

function label = scenario_label(mode)
switch mode
    case 1
        label = 'mode1_hover_ramp';
    case 2
        label = 'mode2_track_only';
    case 3
        label = 'mode3_hover_arm';
    case 4
        label = 'mode4_spiral';
    case 5
        label = 'mode5_track_arm';
    otherwise
        label = sprintf('mode%d_custom', mode);
end
